"""Rebuild the four main-text tables from committed numerical summaries.

Standard library only. No checkpoint, dataset, solver or historical directory.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
ARMS=('D-act','D-tot','M','M-reg')


def table(columns,header,rows,caption,label,hashes):
    return ('% Generated by architecture_closeout_tables.py; '+str(hashes)+'\n'
        '\\begin{table}[ht]\n\\centering\\small\n\\begin{tabular}{'+columns+'}\n\\toprule\n'
        +header+'\\\\\n\\midrule\n'+'\n'.join(' & '.join(r)+'\\\\' for r in rows)
        +'\n\\bottomrule\n\\end{tabular}\n\\caption{'+caption+'}\n\\label{'+label+'}\n\\end{table}\n')


def render(root):
    paths={'s1':root/'docs/architecture_s1_result_20261031.json',
           'primary':root/'paper/results/s2a_primary.json','final':root/'paper/results/s2a_final.json'}
    data={k:json.loads(p.read_text()) for k,p in paths.items()}
    hashes={k:hashlib.sha256(p.read_bytes()).hexdigest() for k,p in paths.items()}
    out={};rows=[]
    for match in ('total','active'):
        r=next(r for r in data['s1']['paired_comparisons'] if r['mode']=='complete' and r['radius']==2 and r['match']==match)
        n=r['denominator'];a,b=r['intervals']['rate_difference'];t=r['median_seconds']
        rows.append([match.capitalize(),f"{round(n*r['rates']['moe'])}/{round(n*r['rates']['dense'])}",
            f"{r['gained']}/{r['lost']}",f"${100*r['rate_difference']:.3f}$ [${100*a:.3f}$,{100*b:.3f}]",
            f"{t['moe']:.3f}/{t['dense']:.3f}"])
    out['s1_primary']=table('lrrrr',r'Dense match & Positives M/D & Gain/loss & $\Delta$ pp [95\% interval] & Median s M/D',rows,
        'Complete numerical positives at $2/255$, each arm out of 600. M/D denotes MoE/dense; all-request costs and input-block intervals retain every seed and outcome.',
        'tab:s1primary',{'s1':hashes['s1']})
    rows=[]
    for name in ARMS:
        r=data['primary']['arms'][name];single=r.get('single_route_fraction')
        rows.append([name.replace('-reg',r'$-$reg'),f"{100*r['clean_accuracy']:.3f}",
            f"{100*r['certified_accuracy']:.3f}",f"{100*r['conditional_positive_fraction']:.2f}",
            '---' if single is None else f'{100*single:.3f}'])
    out['s2_primary']=table('lrrrr',r'Arm & Clean \% & IBP certified \% & Positive/clean \% & Single route \%',rows,
        'S2a at $2/255$: five seeds, each on all 10,000 test images. Primary rates include clean errors. Positive/clean uses each model\'s own correct inputs; it does not define a common population.',
        'tab:s2primary',{'primary':hashes['primary']})
    for mode in ('incomplete','complete'):
        rows=[]
        for name in ARMS:
            r=data['final']['secondary'][mode]['arms'][name];s=r['states']
            assert sum(s.values())==r['denominator']
            row=[name.replace('-reg',r'$-$reg'),str(s['POSITIVE']),f"{100*r['numerical_positive_fraction']:.2f}",
                str(s['UNSAFE_REPLAYED']),str(s['UNKNOWN']),str(s['TIMEOUT'] if mode=='complete' else s['ERROR']),
                f"{r['median_all_request_seconds']:.3f}"]
            if mode=='complete':row.append(f"{r['mean_all_request_seconds']:.3f}")
            rows.append(row)
        caption=('S2a '+('complete verification, 1,000' if mode=='complete' else 'CROWN-IBP, 5,000')+
            ' requests per arm. Positives are numerical-policy results; replayed violations include clean errors. '+
            ('All states and all-request costs are retained; no errors or unexecuted items.' if mode=='complete' else
             'The original error is retained; there are no timeouts or unexecuted items.'))
        header=r'Arm & Positive & Positive \% & Replayed & Unknown & '+('Timeout' if mode=='complete' else 'Error')+' & Median s'
        if mode=='complete':header+=' & Mean s'
        out['s2_'+mode]=table('lrrrrrrr' if mode=='complete' else 'lrrrrrr',header,rows,caption,
            'tab:s2complete' if mode=='complete' else 'tab:s2incomplete',{'final':hashes['final']})
    return out


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');p.add_argument('--root',type=Path,default=ROOT);a=p.parse_args()
    for name,value in render(a.root).items():
        path=a.root/'paper/results'/('closeout_'+name+'.tex')
        if a.check:
            if path.read_text()!=value:raise ValueError('table differs from source: '+str(path))
        else:path.write_text(value)
    print('four main tables '+('checked' if a.check else 'rebuilt')+'; no model calls')
